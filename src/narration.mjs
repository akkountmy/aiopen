/**
 * Реплика между шагами — это ход мысли, а не ответ.
 *
 * Перед вызовом инструментов модель почти всегда говорит что-то вроде
 * «I'll do all three tasks in parallel.» — и раньше такая фраза уходила в ленту
 * первой строкой ответа: пользователь видел английское вступление, а потом уже
 * результат. Правило в промпте это уменьшает, но не убирает: поведение модели
 * недетерминировано, поэтому решение принимаем в коде.
 *
 * Как решаем:
 *  • реплика, начатая латиницей, считается служебной фразой модели и копится
 *    в буфере. Если шаг вызовет инструменты — буфер выбрасывается целиком и в
 *    ленте не остаётся ни строчки; если буфер перерос `hold` знаков, значит это
 *    настоящий ответ на английском — отдаём как обычно;
 *  • всё остальное (кириллица, цифра, markdown, кавычка) — уже ответ, он идёт
 *    в поток сразу, без задержки первого слова;
 *  • что ушло в поток, то попадает и в сохранённый ответ: перезагрузка страницы
 *    не должна показывать другой текст.
 */
export function createNarrationGate({ emit, hold = 320 } = {}) {
  if (typeof emit !== 'function') throw new Error('createNarrationGate: нужен emit');
  const limit = Number.isFinite(hold) && hold > 0 ? hold : 320;
  let pending = '';
  let total = '';
  let live = false;

  function flush() {
    const out = pending;
    pending = '';
    live = true;
    if (out) emit(out);
  }

  return {
    /** Кусок текста от модели: либо копим (латинское начало), либо сразу в поток. */
    push(text) {
      const chunk = String(text ?? '');
      if (!chunk) return;
      total += chunk;
      if (live) {
        emit(chunk);
        return;
      }
      pending += chunk;
      const head = pending.trimStart();
      /* Начало латиницей — кандидат в служебную фразу: держим, пока не станет
         ясно. Любой другой первый знак — это ответ, отдаём немедленно. */
      if (/^[A-Za-z]/.test(head) && head.length <= limit) return;
      flush();
    },

    /**
     * Шаг закончился. `hasToolCalls` — шаг вызвал инструменты, значит реплика
     * была ходом мысли и её не должно остаться ни в ленте, ни в сохранённом
     * ответе. Возвращает текст ответа шага: его дописывают в итог.
     */
    finish(hasToolCalls) {
      if (!live) {
        const held = pending;
        pending = '';
        live = true;
        if (hasToolCalls) return '';
        if (held) emit(held);
        return total;
      }
      pending = '';
      /* Текст уже видел пользователь — он остаётся в ответе, даже если шаг
         закончился инструментами: иначе после перезагрузки текст пропал бы. */
      return total;
    },

    /** Что ещё не отдано в поток (для тестов и отладки). */
    get pending() {
      return pending;
    },
  };
}
