/**
 * Текст для озвучки: разметка прочь, слова — целиком.
 *
 * Зачем отдельный шаг. Документ книги часто приходит с разметкой: markdown
 * (`## Глава 1`, `**важное**`, таблицы с `|`), html-теги из выгрузки, буллиты,
 * линейки `-----`. Синтезатор читает эти знаки вслух — в книге появляется
 * «решётка решётка», «звёздочка звёздочка», «вертикальная черта». Раньше это
 * «лечили» тем, что переписывали текст книги руками и озвучивали сокращённую
 * версию: вместе с решётками из книги пропадали абзацы, которых никто убирать
 * не просил.
 *
 * Правило здесь одно и оно проверяется тестом: этот шаг удаляет только знаки
 * разметки, но не слова. Ни одно слово, число, дата или название не исчезает —
 * на выходе ровно тот же текст книги, только без служебных символов. Поэтому
 * вызывать его можно на любом документе, не спрашивая человека: содержание
 * озвучки от него не меняется.
 *
 * Место в конвейере: первый шаг `normalizeText` в tts.mjs (на нём построены
 * нарезка на куски, оценка длительности и сам синтез). Исходный документ и
 * Word с текстом книги этот шаг не трогает — правка только для голоса.
 */

/* Символы, которые диктор читает по имени, а человек их не произносит:
   эмодзи, пиктограммы, вариационные селекторы, «невидимые» пробелы. */
const PICTURES = /[\u{1F000}-\u{1FAFF}\u{2600}-\u{27BF}\u{2190}-\u{21FF}\u{2B00}-\u{2BFF}\u{FE0F}\u{200B}-\u{200D}\u{FEFF}]/gu;

const ENTITIES = new Map([
  ['&nbsp;', ' '],
  ['&amp;', 'и'],
  ['&lt;', ''],
  ['&gt;', ''],
  ['&quot;', '"'],
  ['&laquo;', '«'],
  ['&raquo;', '»'],
  ['&mdash;', '—'],
  ['&ndash;', '–'],
  ['&hellip;', '…'],
  ['&copy;', ''],
  ['&reg;', ''],
  ['&trade;', ''],
]);

/**
 * Чистит разметку для голоса. Возвращает текст с теми же словами.
 * @param {string} raw
 * @returns {string}
 */
export function speechText(raw) {
  const source = String(raw ?? '');
  if (!source) return '';
  let text = source.replace(/\r\n?/g, '\n');

  /* ── блоки, которые целиком не текст книги ─────────────────────────────── */

  /* Ограждения кода: сама разметка ``` (строки-ограждения) не нужна, а строки
     кода остаются — на случай, если в книге есть пример, который надо услышать. */
  text = text.replace(/^[ \t]*(?:```|~~~)[^\n]*$/gm, '');
  /* Определения сносок «[1]: https://…» — адреса, а не речь. */
  text = text.replace(/^[ \t]*\[[^\]]+\]:[ \t]*\S+[^\n]*$/gm, '');
  /* Линейки разметки: ----- ===== ***** _____. */
  text = text.replace(/^[ \t]*([-*_=—–])(?:[ \t]*\1){2,}[ \t]*$/gm, '');
  /* Разделительные строки таблиц «|---|:---:|---|». */
  text = text.replace(/^[ \t]*\|?[ \t:|-]{3,}\|?[ \t]*$/gm, '');
  /* Колонтитулы и метаданные разбора docx — их диктор тоже читал вслух. */
  text = text.replace(/^\[(?:Колонтитул|Нижний колонтитул)\][^\n]*$/gm, '');
  text = text.replace(/^Заголовок документа:[^\n]*$/gm, '');

  /* ── внутристрочная разметка ───────────────────────────────────────────── */

  /* html-теги из выгрузок и вставок из браузера. */
  text = text.replace(/<\/?[a-zA-Z][^>\n]{0,200}>/g, '');
  text = text.replace(/<!--[\s\S]*?-->/g, '');
  for (const [entity, replacement] of ENTITIES) text = text.split(entity).join(replacement);
  text = text.replace(/&#(\d{2,5});/g, (_, code) => {
    const value = Number(code);
    return value > 31 && value < 0x3000 ? String.fromCodePoint(value) : ' ';
  });

  /* Картинки и ссылки: остаётся подпись, адрес не читаем. */
  text = text.replace(/!\[([^\]\n]*)\]\([^)\n]*\)/g, '$1');
  text = text.replace(/\[([^\]\n]+)\]\([^)\n]*\)/g, '$1');
  text = text.replace(/\[([^\]\n]+)\]\[[^\]\n]*\]/g, '$1');
  /* Адреса, которые остались без разметки, и почта — не речь: диктор читает их
     по буквам («х-т-т-п»). Лучше убрать целиком, чем слушать алфавит. */
  text = text.replace(/\bhttps?:\/\/[^\s<>()"']+/gi, ' ');
  text = text.replace(/\bwww\.[^\s<>()"']+/gi, ' ');
  text = text.replace(/\b[\w.+-]+@[\w.-]+\.[a-zа-я]{2,}\b/gi, ' ');

  /* Акценты: *****жирный курсив*****, **жирный**, *курсив*, __, _, ~~зачёркнутый~~. */
  text = text.replace(/\*{3}([^*\n]+)\*{3}/g, '$1');
  text = text.replace(/\*{2}([^*\n]+)\*{2}/g, '$1');
  text = text.replace(/_{2}([^_\n]+)_{2}/g, '$1');
  text = text.replace(/~~([^~\n]+)~~/g, '$1');
  /* Одиночные звёздочки и подчёркивания — только парные и только на границе
     слова: иначе пострадают snake_case и «2 * 3». */
  text = text.replace(/(?<![\p{L}\p{N}*])\*([^*\s][^*\n]*?)\*(?![\p{L}\p{N}*])/gu, '$1');
  text = text.replace(/(?<![\p{L}\p{N}_])_([^_\s][^_\n]*?)_(?![\p{L}\p{N}_])/gu, '$1');
  /* Строчный код: обратные кавычки — разметка, содержимое — текст. */
  text = text.replace(/`([^`\n]*)`/g, '$1');

  /* ── построчная разметка ───────────────────────────────────────────────── */

  /* Заголовки: «### Глава первая» → «Глава первая» (и закрывающие решётки). */
  text = text.replace(/^[ \t]*#{1,6}[ \t]*/gm, '');
  text = text.replace(/[ \t]+#{1,6}[ \t]*$/gm, '');
  /* Цитаты. */
  text = text.replace(/^[ \t]*>[ \t]?/gm, '');
  /* Буллиты и чек-боксы списков. Тире в диалоге («— Здравствуйте») не трогаем:
     это авторская пунктуация, а не разметка. */
  text = text.replace(/^[ \t]*[-+•·▪◦][ \t]+/gm, '');
  text = text.replace(/^[ \t]*\*[ \t]+/gm, '');
  text = text.replace(/^[ \t]*\[[ xX]\][ \t]*/gm, '');
  /* Таблица: вертикальные черты — границы ячеек, а не «вертикальная черта». */
  text = text.replace(/\|/g, ' ');

  /* ── служебные знаки, которые диктор называет вслух ────────────────────── */

  /* Сноска «[1]» — не слово «один»; квадратные скобки — не «скобка». */
  text = text.replace(/\[\d{1,3}\]/g, '');
  text = text.replace(/[#^~\\<>{}]/g, ' ');
  text = text.replace(/\[|\]/g, ' ');
  text = text.replace(/©|®|™/g, '');
  /* Маркеры списков, которые остались внутри строки, — пауза, а не «точка». */
  text = text.replace(/[•·▪◦‣∙]/g, ' ');
  /* «№ 5» и «§ 3» человек произносит словами, а не «знак номера». */
  text = text.replace(/№[ \t]*/g, 'номер ');
  text = text.replace(/§[ \t]*/g, 'параграф ');
  /* Тире и дефис как знак препинания: диктор говорит «тире»/«дефис» или
     делает неестественную паузу. В начале строки (диалог) тире убираем,
     внутри — заменяем запятой: смысл тот же, звук чище. Дефис внутри слова
     («по-русски», «snake_case») остаётся. */
  text = text.replace(/^[ \t]*[—–]+[ \t]*/gm, '');
  text = text.replace(/[ \t]*[—–][ \t]*/g, ', ');
  text = text.replace(/[ \t]+-[ \t]+/g, ', ');
  text = text.replace(/[ \t]*--+[ \t]*/g, ', ');

  /* ── остатки символов разметки ─────────────────────────────────────────── */

  /* Звёздочка между цифрами — это знак умножения («2 * 3 = 6»), а не разметка:
     её прячем на время чистки, иначе из примера в книге пропадало умножение. */
  text = text.replace(/(\d[ \t]*)\*([ \t]*\d)/g, '$1\uE000$2');
  /* Подчёркивание внутри слова — часть имени (`snake_case`), а не разметка:
     вырезаем только те подчёркивания, что стоят на границе слова. */
  text = text.replace(/[*~`]+/g, '');
  text = text.replace(/(?<![\p{L}\p{N}])_+|_+(?![\p{L}\p{N}])/gu, '');
  text = text.replace(/\uE000/g, '*');
  text = text.replace(PICTURES, '');

  /* ── пробелы ───────────────────────────────────────────────────────────── */

  text = text.replace(/[ \t\u00a0]+/g, ' ');
  text = text.replace(/[ \t]+$/gm, '');
  /* Пробел перед знаком препинания после вырезанного символа: «слово ,» → «слово,». */
  text = text.replace(/[ \t]+([,.;:!?…%)\]»])/g, '$1');
  text = text.replace(/([(\[«])[ \t]+/g, '$1');
  /* Запятые, оставшиеся от тире и вырезанных символов. */
  text = text.replace(/,\s*,+/g, ',');
  text = text.replace(/(^|\n)[ \t]*,+[ \t]*/g, '$1');
  text = text.replace(/,[ \t]*([.!?…])/g, '$1');
  /* Три и больше пустых строк — это уже не абзацы, а мусор от вырезанных строк. */
  text = text.replace(/\n{3,}/g, '\n\n');

  const cleaned = text.trim();
  /* Страховка: если от текста не осталось ничего, а он был, — не отдаём пустоту,
     а возвращаем исходник. Потерять книгу хуже, чем прочитать лишний символ. */
  if (!cleaned && source.trim()) return source;
  return cleaned;
}
