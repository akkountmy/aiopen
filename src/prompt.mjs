export function documentAttachmentNote({ name, kind, text, warnings }) {
  const head = `[Документ «${name}», тип: ${kind}]`;
  const tail = warnings && warnings.length ? `\n(примечания: ${warnings.join(' ')})` : '';
  return `${head}\n${text}${tail}`;
}

