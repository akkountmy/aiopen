/** Какие экспертные стандарты подходят к текущей просьбе (не больше двух). */
export function expertBlocks(question) {
  const text = String(question || '').toLowerCase();
  if (!text) return [];
  const matched = EXPERT_MODES.filter(
    (mode) =>
      mode.words.some((word) => text.includes(word)) &&
      /* Тема, названная точнее, исключает соседний блок: «дизайн интерьера» — это не веб-дизайн. */
      !(mode.skip || []).some((word) => text.includes(word)),
  );
  return matched.slice(0, 2).map((mode) => ({ id: mode.id, lines: mode.lines }));
}

